const API="https://mason-learning-api.yuanting0117a.workers.dev";
const $=id=>document.getElementById(id);
let video=null,feedUrl="";
const appPassword=()=>$("appPassword").value.trim();
const endpoint=path=>API.replace(/\/$/,"")+path;
function status(id,msg,type=""){const el=$(id);el.textContent=msg;el.className="status "+type}
$("fetch").onclick=async()=>{
 const url=$("url").value.trim();if(!url)return status("status","請先貼上 YouTube 網址。","error");
 $("fetch").disabled=true;status("status","正在讀取影片資訊……");
 try{
  const r=await fetch(endpoint("/api/video?url="+encodeURIComponent(url)));
  const d=await r.json();if(!r.ok)throw Error(d.error||"影片資訊讀取失敗");
  video=d;$("meta").classList.remove("hidden");$("title").textContent=d.title||"未取得";$("published").textContent=d.publishedAt||"未提供";$("vid").textContent=d.videoId||"";
  try{
   const tr=await fetch(endpoint("/api/transcript?url="+encodeURIComponent(url)+"&lang=en"));
   const td=await tr.json();if(!tr.ok)throw Error(td.error||"字幕讀取失敗");
   $("transcript").value=td.text;$("captionInfo").textContent=td.segments.length+" 個字幕片段 · "+td.language+(td.isAutoGenerated?" · 自動字幕":"");
   status("status","影片資訊與字幕已載入，請檢查逐字稿。","ok");
  }catch(e){$("captionInfo").textContent="字幕尚未取得";status("status","影片資訊已取得，但字幕讀取失敗："+e.message+" 請貼上 YouTube Gemini 逐字稿。","error")}
 }catch(e){status("status",e.message,"error")}finally{$("fetch").disabled=false}
};
$("copyTranscript").onclick=async()=>{try{await navigator.clipboard.writeText($("transcript").value);status("status","逐字稿已複製。","ok")}catch{status("status","複製失敗，請手動選取。","error")}};
$("queue").onclick=async()=>{
 const url=$("url").value.trim(),transcript=$("transcript").value.trim();
 if(!url||!transcript)return status("queueStatus","請確認影片網址與英文逐字稿都已填寫。","error");
 if(!appPassword())return status("queueStatus","請先輸入網站存取密碼。","error");
 $("queue").disabled=true;status("queueStatus","正在保存到待整理區……");
 try{const r=await fetch(endpoint("/api/queue"),{method:"POST",headers:{"Content-Type":"application/json","X-App-Password":appPassword()},body:JSON.stringify({url,transcript,video})});const d=await r.json();if(!r.ok)throw Error(d.error||"保存失敗");status("queueStatus",d.duplicate?"這部影片已在待整理區，沒有重複新增。":"影片網址與逐字稿已保存。","ok");}catch(e){status("queueStatus",e.message,"error")}finally{$("queue").disabled=false}
};
async function loadPending(){
 const key=$("gptReadKey").value.trim();if(!key)return status("pendingStatus","請輸入 Cloudflare 的 GPT_READ_KEY。","error");
 $("loadPending").disabled=true;status("pendingStatus","正在讀取待整理資料……");
 try{const r=await fetch(endpoint("/api/pending"),{headers:{"Authorization":"Bearer "+key}});const d=await r.json();if(!r.ok)throw Error(d.error||"讀取失敗");renderPending(d.items||[]);status("pendingStatus","目前有 "+(d.count||0)+" 部待整理影片。","ok");}
 catch(e){status("pendingStatus",e.message,"error");$("pendingList").innerHTML=""}finally{$("loadPending").disabled=false}
}
function renderPending(items){
 const root=$("pendingList");root.innerHTML="";
 if(!items.length){root.innerHTML='<p class="empty">目前沒有待整理影片。</p>';return}
 for(const item of items){const card=document.createElement("article");card.className="pending-card";const title=document.createElement("h3");title.textContent=item.title||"未命名影片";const meta=document.createElement("p");meta.className="pending-meta";meta.textContent="建立時間："+(item.createdAt?new Date(item.createdAt).toLocaleString("zh-TW"):"未知");const link=document.createElement("a");link.href=item.url||"#";link.target="_blank";link.rel="noopener";link.textContent="開啟 YouTube 影片 ↗";const details=document.createElement("details");const summary=document.createElement("summary");summary.textContent="查看英文逐字稿";const body=document.createElement("pre");body.textContent=item.transcript||"（沒有逐字稿）";details.append(summary,body);card.append(title,meta,link,details);root.append(card)}
}
$("loadPending").onclick=loadPending;$("refreshPending").onclick=loadPending;
