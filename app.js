async function markImported(id){
 const input=$("notion-"+id),notionUrl=input?.value.trim(),password=$("appPassword").value.trim();
 if(!notionUrl)return alert("請先貼上 GPT 回報的 Notion 頁面連結。");
 try{
  const r=await fetch(endpoint("/api/mark-imported"),{method:"POST",headers:{"Content-Type":"application/json","X-App-Password":password},body:JSON.stringify({id,notionUrl})}),d=await r.json();
  if(!r.ok)throw Error(d.error||"更新失敗");
  status("saveStatus","已更新為「已匯入 Notion」。","ok");await loadLibrary();
 }catch(e){alert(e.message)}
}
